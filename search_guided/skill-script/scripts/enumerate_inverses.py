def _func_node(tree: ast.AST, name: str):
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == name:
            return node
    return None


def _is_bool_param(func: ast.FunctionDef, name: str) -> bool:
    """True if `name` is a parameter with a bool default."""
    args = func.args
    defaults = [None] * (len(args.args) - len(args.defaults)) + list(args.defaults)
    for a, d in zip(args.args, defaults):
        if a.arg == name and isinstance(d, ast.Constant) and type(d.value) is bool:
            return True
    return False


def _scope_names(func: ast.FunctionDef) -> list[str]:
    """In-scope value names in first-appearance order: params, then
    assigned names (Assign / AugAssign / For / NamedExpr targets).
    Bool parameters are excluded (flags, not values)."""
    names: list[str] = []
    for a in func.args.args:
        if not _is_bool_param(func, a.arg) and a.arg not in names:
            names.append(a.arg)
    for sub in _iter_dfs(func):
        if isinstance(sub, ast.Assign):
            for t in sub.targets:
                for n in ast.walk(t):
                    if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Store) and n.id not in names:
                        names.append(n.id)
        elif isinstance(sub, ast.AugAssign) and isinstance(sub.target, ast.Name):
            if sub.target.id not in names:
                names.append(sub.target.id)
        elif isinstance(sub, ast.For) and isinstance(sub.target, ast.Name):
            if sub.target.id not in names:
                names.append(sub.target.id)
    return names


def _params(func: ast.FunctionDef) -> list[str]:
    return [a.arg for a in func.args.args if not _is_bool_param(func, a.arg)]


def _last_assigned_local(func: ast.FunctionDef, before_lineno: int) -> str | None:
    """Last single-Name assignment target textually before the line."""
    last = None
    for sub in _iter_dfs(func):
        if isinstance(sub, ast.Assign) and len(sub.targets) == 1 and isinstance(sub.targets[0], ast.Name):
            if sub.lineno < before_lineno:
                last = sub.targets[0].id
    return last


def _bare_returns(func: ast.FunctionDef) -> list[dict]:
    """Bare `return` statements in the function. is_end: it is the
    function's final statement. in_guard: it sits inside an If."""
    out = []
    body_end = func.body[-1].lineno if func.body else -1
    for sub in _iter_dfs(func):
        if isinstance(sub, ast.Return) and sub.value is None:
            in_guard = False
            for node in ast.walk(func):
                if isinstance(node, ast.If):
                    for s in _iter_dfs(node):
                        if s is sub:
                            in_guard = True
            out.append({"lineno": sub.lineno, "is_end": sub.lineno == body_end,
                        "in_guard": in_guard})
    return out


def _pass_sites(func: ast.FunctionDef) -> list[int]:
    return [sub.lineno for sub in _iter_dfs(func) if isinstance(sub, ast.Pass)]


def _bare_bool_guards(func: ast.FunctionDef) -> list[dict]:
    """`if <Name>:` guards where Name is a bool parameter."""
    out = []
    for sub in _iter_dfs(func):
        if isinstance(sub, ast.If) and isinstance(sub.test, ast.Name):
            if _is_bool_param(func, sub.test.id):
                out.append({"lineno": sub.lineno, "name": sub.test.id})
    return out


def _other_function_exprs(tree: ast.AST, exclude: str) -> list[str]:
    """RHS / return-value expressions from functions other than
    `exclude`, in file order, deduplicated, as source strings."""
    out: list[str] = []
    for node in _iter_dfs(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name != exclude:
            for sub in _iter_dfs(node):
                if isinstance(sub, ast.Assign):
                    s = ast.unparse(sub.value)
                    if s not in out:
                        out.append(s)
                elif isinstance(sub, ast.Return) and sub.value is not None:
                    s = ast.unparse(sub.value)
                    if s not in out:
                        out.append(s)
    return out


def _other_function_consts(tree: ast.AST, exclude: str) -> list:
    """Distinct numeric (int/float, not bool) constants appearing in
    functions other than `exclude`, in file order."""
    out: list = []
    for node in _iter_dfs(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name != exclude:
            for sub in _iter_dfs(node):
                if isinstance(sub, ast.Constant) and isinstance(sub.value, (int, float)) and type(sub.value) is not bool:
                    if sub.value not in out:
                        out.append(sub.value)
    return out


def _assigned_names(func: ast.FunctionDef) -> set[str]:
    out: set[str] = set()
    for sub in _iter_dfs(func):
        if isinstance(sub, ast.Assign):
            for t in sub.targets:
                for n in ast.walk(t):
                    if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Store):
                        out.add(n.id)
        elif isinstance(sub, (ast.AugAssign, ast.For)):
            tgt = sub.target
            if isinstance(tgt, ast.Name):
                out.add(tgt.id)
    return out


def _loaded_after(func: ast.FunctionDef, lineno: int) -> list[str]:
    """Names loaded after the given line, in first-use order."""
    out: list[str] = []
    for sub in _iter_dfs(func):
        if isinstance(sub, ast.Name) and isinstance(sub.ctx, ast.Load) and sub.lineno > lineno:
            if sub.id not in out:
                out.append(sub.id)
    return out


def _never_assigned_load_after(func: ast.FunctionDef, lineno: int) -> list[str]:
    """Names loaded after the given line that are neither parameters
    nor assigned anywhere in the function — a name the function
    uses but never defines locally. (Covers the collision case:
    the removed local shares its name with a module-level helper,
    so the probe raises TypeError instead of NameError.)"""
    assigned = _assigned_names(func)
    params = {a.arg for a in func.args.args}
    return [n for n in _loaded_after(func, lineno)
            if n not in assigned and n not in params]


# ---------------------------------------------------------------------------
# Candidate construction (ported from v3 sim). Each builder returns a
# list of dicts with keys inverse/site/param/source/detail/phase.
# Sources are built by editing a deepcopy of the tree and unparsing
# (same pattern as search_baseline._recon_candidates). Expression
# strings are parsed with mode='eval' and spliced in.
# ---------------------------------------------------------------------------
def _with_return(tree: ast.AST, lineno: int, expr_src: str) -> str | None:
    new_tree = copy.deepcopy(tree)
    for sub in _iter_dfs(new_tree):
        if isinstance(sub, ast.Return) and sub.lineno == lineno:
            sub.value = ast.parse(expr_src, mode="eval").body
            break
    else:
        return None
    ast.fix_missing_locations(new_tree)
    cand = ast.unparse(new_tree)
    ast.parse(cand)
    return cand


def _with_assign(tree: ast.AST, lineno: int, target: str, rhs_src: str) -> str | None:
    new_tree = copy.deepcopy(tree)
    for sub in _iter_dfs(new_tree):
        if isinstance(sub, ast.Pass) and sub.lineno == lineno:
            assign = ast.Assign(
                targets=[ast.Name(id=target, ctx=ast.Store())],
                value=ast.parse(rhs_src, mode="eval").body,
            )
            ast.copy_location(assign, sub)
            # Replace the Pass node in its parent body list.
            for parent in _iter_dfs(new_tree):
                for field in ("body", "orelse", "finalbody"):
                    stmts = getattr(parent, field, None)
                    if isinstance(stmts, list):
                        for i, stmt in enumerate(stmts):
                            if stmt is sub:
                                stmts[i] = assign
                                ast.fix_missing_locations(new_tree)
                                cand = ast.unparse(new_tree)
                                ast.parse(cand)
                                return cand
    return None


def _with_guard(tree: ast.AST, lineno: int, guard_name: str, extra_src: str, joiner: str) -> str | None:
    new_tree = copy.deepcopy(tree)
    for sub in _iter_dfs(new_tree):
        if isinstance(sub, ast.If) and sub.lineno == lineno and isinstance(sub.test, ast.Name):
            extra = ast.parse(extra_src, mode="eval").body
            op = ast.And() if joiner == "and" else ast.Or()
            sub.test = ast.BoolOp(op=op, values=[ast.Name(id=guard_name, ctx=ast.Load()), extra])
            ast.fix_missing_locations(new_tree)
            cand = ast.unparse(new_tree)
            ast.parse(cand)
            return cand
    return None


def _pair_binops(names: list[str], anchor_first: list[str] | None = None) -> list[str]:
    """Ordered pairs of distinct names x ops, as expression strings.
    If anchor_first is given, only pairs whose FIRST element is in
    it (used for last-local-anchored BinOps: anchor is the last
    local, second element any name)."""
    out: list[str] = []
    for a in names:
        if anchor_first is not None and a not in anchor_first:
            continue
        for b in names:
            if b == a:
                continue
            for op in BINOPS:
                out.append(f"{a} {op} {b}")
    return out


def phase0_candidates(tree: ast.AST, impl: set[str], symptom: dict) -> list[dict]:
    """R0 symptom-first (fires only when the failing test returns
    None): last-local guess for end bare returns, then the expected
    literal for guard-branch bare returns."""
    if not symptom["returns_none"]:
        return []
    out: list[dict] = []
    for fname in sorted(impl):
        func = _func_node(tree, fname)
        if func is None:
            continue
        for ret in _bare_returns(func):
            if ret["is_end"]:
                last = _last_assigned_local(func, ret["lineno"])
                if last:
                    src = _with_return(tree, ret["lineno"], last)
                    if src:
                        out.append({"inverse": RECON_KEY, "site": ret["lineno"],
                                    "param": last, "source": src, "phase": "P0-guess",
                                    "detail": f"R0: return {last} (last assigned local before line {ret['lineno']})"})
            elif ret["in_guard"]:
                exp = symptom["expected"]
                if isinstance(exp, (int, float, str, bool)) and exp is not None:
                    lit = repr(exp)
                    src = _with_return(tree, ret["lineno"], lit)
                    if src:
                        out.append({"inverse": "recon_guard_literal", "site": ret["lineno"],
                                    "param": lit, "source": src, "phase": "P0-guard-literal",
                                    "detail": f"R0: guard-branch bare return -> return {lit} (failing test expects {lit})"})
    return out


def recon_return_candidates(tree: ast.AST, impl: set[str]) -> list[dict]:
    """R1: recomputed-expression variants for end-of-function bare
    returns. Ordered simplest-first; see SKILL.md."""
    out: list[dict] = []
    for fname in sorted(impl):
        func = _func_node(tree, fname)
        if func is None:
            continue
        for ret in _bare_returns(func):
            if not ret["is_end"]:
                continue
            names = _scope_names(func)
            params = _params(func)
            last = _last_assigned_local(func, ret["lineno"])
            exprs: list[tuple[str, str]] = []  # (expr, detail)
            # (a0) same-file reuse.
            for e in _other_function_exprs(tree, fname):
                exprs.append((e, f"reuse expr from another function in the file: {e}"))
            # (a) last-local-anchored BinOps.
            if last:
                for e in _pair_binops(names, anchor_first=[last]):
                    exprs.append((e, f"recomputed return: {e}"))
            # (b) return <name> for each other in-scope name.
            for n in names:
                if n != last:
                    exprs.append((n, f"return {n}"))
            # (c) param-involving pair BinOps.
            for a in names:
                for b in names:
                    if b == a or (a not in params and b not in params):
                        continue
                    for op in BINOPS:
                        exprs.append((f"{a} {op} {b}", f"recomputed return: {a} {op} {b}"))
            # (d) 3-operand left-assoc chains over non-bool params.
            if 2 <= len(params) <= 3:
                for trip in itertools.permutations(params, 3):
                    for ops in (("*", "*"), ("*", "/"), ("/", "*"), ("/", "/"),
                                ("+", "+"), ("+", "-"), ("-", "+"), ("-", "-")):
                        exprs.append((f"({trip[0]} {ops[0]} {trip[1]}) {ops[1]} {trip[2]}",
                                      f"recomputed return: {trip[0]} {ops[0]} {trip[1]} {ops[1]} {trip[2]}"))
            # (e) name-const BinOps (consts from other functions).
            for c in _other_function_consts(tree, fname):
                for n in names:
                    for op in BINOPS:
                        exprs.append((f"{n} {op} {c}", f"recomputed return: {n} {op} {c}"))
            seen: set[str] = set()
            for expr, detail in exprs:
                if expr in seen:
                    continue
                seen.add(expr)
                src = _with_return(tree, ret["lineno"], expr)
                if src:
                    out.append({"inverse": "recon_return_expr", "site": ret["lineno"],
                                "param": expr, "source": src, "phase": "R1-return-expr",
                                "detail": detail})
    return out


def recon_assign_candidates(tree: ast.AST, impl: set[str], symptom: dict) -> list[dict]:
    """R2: removed-assignment re-insertion, per `pass` site."""
    out: list[dict] = []
    for fname in sorted(impl):
        func = _func_node(tree, fname)
        if func is None:
            continue
        names = _scope_names(func)
        params = _params(func)
        assigned = _assigned_names(func)
        for lineno in _pass_sites(func):
            # Target: (1) the name in the NameError/UnboundLocalError
            # raised by the failing call (read off the test output);
            # (2) a name the function loads after the `pass` but
            # never defines locally (collision case: the removed
            # local shares its name with a module-level helper, so
            # the probe raises TypeError instead); (3) the first
            # name loaded after the `pass` that is assigned
            # somewhere in the function (re-assignment case: the
            # pass sits where an accumulator update was).
            target = symptom["name_error"]
            if not target:
                never = _never_assigned_load_after(func, lineno)
                if never:
                    target = never[0]
            if not target:
                for n in _loaded_after(func, lineno):
                    if n in assigned:
                        target = n
                        break
            if not target:
                continue
            rhs: list[tuple[str, str]] = []
            # (1) same-file reuse.
            for e in _other_function_exprs(tree, fname):
                rhs.append((e, f"reuse expr from another function in the file: {e}"))
            # (2) simple: params, constants, other locals.
            for p in params:
                rhs.append((p, f"re-insert {target} = {p}"))
            for c in SIMPLE_CONSTS:
                rhs.append((c, f"re-insert {target} = {c}"))
            for n in names:
                if n != target:
                    rhs.append((n, f"re-insert {target} = {n}"))
            # (3) len/sum calls.
            for n in names:
                rhs.append((f"len({n})", f"re-insert {target} = len({n})"))
                rhs.append((f"sum({n})", f"re-insert {target} = sum({n})"))
            # (4) target-anchored BinOps.
            for e in _pair_binops(names, anchor_first=[target]):
                rhs.append((e, f"re-insert {target} = {e}"))
            for b in names:
                if b == target:
                    continue
                for op in BINOPS:
                    rhs.append((f"{b} {op} {target}", f"re-insert {target} = {b} {op} {target}"))
            # (5) param-involving pair BinOps.
            for a in names:
                for b in names:
                    if b == a or (a not in params and b not in params):
                        continue
                    for op in BINOPS:
                        rhs.append((f"{a} {op} {b}", f"re-insert {target} = {a} {op} {b}"))
            # (6) name-const BinOps.
            for c in _other_function_consts(tree, fname):
                for n in names:
                    for op in BINOPS:
                        rhs.append((f"{n} {op} {c}", f"re-insert {target} = {n} {op} {c}"))
            seen: set[str] = set()
            for expr, detail in rhs:
                if expr in seen:
                    continue
                seen.add(expr)
                src = _with_assign(tree, lineno, target, expr)
                if src:
                    out.append({"inverse": "recon_assign", "site": lineno,
                                "param": f"{target} = {expr}", "source": src,
                                "phase": "R2-assign", "detail": detail})
    return out


def recon_guard_candidates(tree: ast.AST, impl: set[str]) -> list[dict]:
    """R3: dropped-condition guard re-insertion (true-repair
    attempt). Guard is a bare bool parameter; re-insert an operand
    inferred from the boundary input / in-scope names."""
    out: list[dict] = []
    for fname in sorted(impl):
        func = _func_node(tree, fname)
        if func is None:
            continue
        names = _scope_names(func)
        consts = [0] + [c for c in _other_function_consts(tree, fname) if c != 0]
        for g in _bare_bool_guards(func):
            for joiner in ("and", "or"):
                for x in names:
                    for cmp in CMP_ORDER:
                        for c in consts:
                            extra = f"{x} {cmp} {c}"
                            src = _with_guard(tree, g["lineno"], g["name"], extra, joiner)
                            if src:
                                out.append({"inverse": "recon_guard", "site": g["lineno"],
                                            "param": f"{g['name']} {joiner} {extra}",
                                            "source": src, "phase": "R3-guard",
                                            "detail": f"re-insert guard: {g['name']} {joiner} {extra}"})
    return out


def build_combined_order(buggy: str, impl: set[str], symptom: dict) -> list[dict]:
    """The v3 combined order: P0 symptom-first, enumeration in
    prompt order P (in-region only), R1, R2, R3. Dedup by patched
    source, first occurrence wins (the P0 guess is the same
    candidate as the RECON_KEY entry at the end of order P; it is
    not retried)."""
    tree = ast.parse(buggy)
    site_map = map_sites_to_functions(tree)
    all_cands = generate_candidates(buggy)

    annotated = []
    for cand in all_cands:
        if cand["inverse"] == RECON_KEY:
            pos = (cand["site"], 0)
            func = None
            for node in _iter_dfs(tree):
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    end = getattr(node, "end_lineno", None) or node.lineno
                    if node.lineno <= cand["site"] <= end:
                        func = node.name
            in_region = func in impl if impl else True
            inv_order = len(TRUE_INVERSES)
            param_order = 0
        else:
            func, lineno, col = site_map[(cand["inverse"], cand["site"])]
            pos = (lineno, col)
            in_region = func in impl if impl else True
            inv_order = TRUE_INVERSES.index(cand["inverse"])
            param_order = _inverse_params(cand["inverse"]).index(cand["param"])
        annotated.append({**cand, "func": func, "pos": pos,
                          "in_region": in_region, "inv_order": inv_order,
                          "param_order": param_order})

    in_region = [c for c in annotated if c["in_region"]]

    def _prompt_key(cand):
        inv = cand["inverse"]
        rank = PROMPT_INVERSE_ORDER.index(inv)
        param_rank = 0 if inv == RECON_KEY else _inverse_params(inv).index(cand["param"])
        return (rank, cand["site"], param_rank)

    order_p = sorted(in_region, key=_prompt_key)

    p0 = phase0_candidates(tree, impl, symptom)
    r1 = recon_return_candidates(tree, impl)
    r2 = recon_assign_candidates(tree, impl, symptom)
    r3 = recon_guard_candidates(tree, impl)

    combined: list[dict] = []
    seen_src: set[str] = set()
    for cand in p0 + order_p + r1 + r2 + r3:
        src = cand["source"]
        if src in seen_src:
            continue
        seen_src.add(src)
        combined.append({**cand, "phase": cand.get("phase", "P1-enum")})
    counts = {
        "n_phase0": len(p0), "n_enum_in_region": len(order_p),
        "n_recon_r1": len(r1), "n_recon_r2": len(r2),
        "n_recon_r3": len(r3), "n_combined": len(combined),
    }
    return combined, counts


# ---------------------------------------------------------------------------
# Test running with the fixed-harness semantics (ported from
# harness/test_runner.py): every run deletes all __pycache__ dirs
# under cwd first AND runs with bytecode writing disabled, because
# CPython validates a .pyc by (mtime in whole seconds, size) and a
# same-size same-second rewrite would otherwise load stale bytecode.
# Pass/fail is the command's exit code (unittest and pytest both
# exit 0 only when everything they ran passed).
# ---------------------------------------------------------------------------
def _clear_pycache(cwd: str) -> None:
    for root, dirs, _files in os.walk(cwd):
        for d in list(dirs):
            if d == "__pycache__":
                shutil.rmtree(os.path.join(root, d), ignore_errors=True)
                dirs.remove(d)


def _run_cmd(cmd: str, cwd: str, timeout: int) -> tuple[bool, str, float]:
    t0 = time.monotonic()
    _clear_pycache(cwd)
    env = dict(os.environ)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    try:
        proc = subprocess.run(
            shlex.split(cmd), cwd=cwd, capture_output=True, text=True,
            timeout=timeout, env=env,
        )
        out = (proc.stdout + proc.stderr)[-2000:]
        return proc.returncode == 0, out, time.monotonic() - t0
    except subprocess.TimeoutExpired:
        return False, f"TIMEOUT after {timeout}s", time.monotonic() - t0
    except Exception as e:  # noqa: BLE001 - a command that cannot run at all is a failure, not a crash
        return False, f"ERROR: {e}", time.monotonic() - t0


# ---------------------------------------------------------------------------
# Minimal edit-spec construction. The script returns the fix as an
# edit the agent applies with edit_file — it never leaves a
# rewritten file behind. Candidates are generated by AST transform
# + ast.unparse, which would reformat a real (non-normalized) file
# if left in place, so the edit must be minimal and verified:
# applying old_text -> new_text to the ORIGINAL source must itself
# pass the failing test and the regressions (checked by the caller
# loop before the candidate is reported).
# ---------------------------------------------------------------------------
def _line_offsets(source: str) -> list[int]:
    offs = [0]
    for line in source.splitlines(keepends=True):
        offs.append(offs[-1] + len(line))
    return offs


def _splice(source: str, node: ast.AST, replacement: str) -> str | None:
    """Replace the exact source span of `node` with `replacement`.
    Returns None when the node has no position info or the result
    does not parse (e.g. a parenthesised operand's span included a
    stray parenthesis)."""
    offs = _line_offsets(source)
    try:
        start = offs[node.lineno - 1] + node.col_offset
        end = offs[node.end_lineno - 1] + node.end_col_offset
    except (AttributeError, IndexError, TypeError):
        return None
    new = source[:start] + replacement + source[end:]
    if new == source:
        return None
    try:
        ast.parse(new)
    except SyntaxError:
        return None
    return new


def _with_context(original: str, new_source: str, first: int, last: int):
    """old/new text for lines [first, last) (0-indexed, half-open)
    in the original / new source, widened with context lines until
    old_text occurs exactly once in the original (max 3 lines each
    side). Returns (old_text, new_text) or None."""
    orig_lines = original.splitlines(keepends=True)
    new_lines = new_source.splitlines(keepends=True)
    for ctx in range(0, 4):
        a = max(0, first - ctx)
        b = min(len(orig_lines), last + ctx)
        # Lines outside the changed region are identical in both
        # sources (single change block), so the same indices apply.
        old_text = "".join(orig_lines[a:b])
        new_text = "".join(new_lines[a:b])
        if old_text and original.count(old_text) == 1:
            return old_text, new_text
    return None


def _diff_edit_spec(original: str, candidate: str):
    """Minimal edit spec via difflib between the original source and
    the candidate (unparsed) source. Accepted only when the diff is
    a single contiguous block of at most 4 lines each side — i.e.
    the file is unparse-normalized and the candidate changes one
    site. Returns (old_text, new_text) or None."""
    orig_lines = original.splitlines(keepends=True)
    cand_lines = candidate.splitlines(keepends=True)
    sm = difflib.SequenceMatcher(a=orig_lines, b=cand_lines, autojunk=False)
    changes = [op for op in sm.get_opcodes() if op[0] != "equal"]
    if len(changes) != 1:
        return None
    _tag, i1, i2, j1, j2 = changes[0]
    if (i2 - i1) > 4 or (j2 - j1) > 4:
        return None
    return _with_context(original, candidate, i1, i2)


def _find_inverse_node(tree: ast.AST, inverse: str, site: int):
    """Locate the site-th matching node for `inverse` in DFS
    pre-order — the same counting _Inverter/_count_sites use (a
    negative int literal is one site; its inner Constant is never
    a separate site)."""
    seen = [-1]
    result: list = [None]

    def walk(node: ast.AST):
        if result[0] is not None:
            return
        if inverse in ("off_by_one", "wrong_constant") and _is_neg_int_literal(node):
            seen[0] += 1
            if seen[0] == site:
                result[0] = node
            return  # do not descend into the inner Constant(1)
        if _site_matches(node, inverse):
            seen[0] += 1
            if seen[0] == site:
                result[0] = node
                return
        for child in ast.iter_child_nodes(node):
            if _is_neg_int_literal(node) and isinstance(child, ast.Constant):
                continue
            walk(child)
            if result[0] is not None:
                return

    walk(tree)
    return result[0]


def _find_stmt_at(tree: ast.AST, kind: type, lineno: int):
    for node in _iter_dfs(tree):
        if isinstance(node, kind) and node.lineno == lineno:
            return node
    return None


def _span_replacement(tree: ast.AST, cand: dict) -> tuple | None:
    """(node, replacement) for a candidate, for the span-splice
    fallback. Returns None when the node cannot be located or the
    replacement cannot be built."""
    inv, site, param = cand["inverse"], cand["site"], cand["param"]
    if inv in TRUE_INVERSES:
        node = _find_inverse_node(tree, inv, site)
        if node is None:
            return None
        if inv in ("off_by_one", "wrong_constant"):
            if isinstance(node, ast.UnaryOp):
                value = _neg_int_value(node) + param
            else:
                value = node.value + param
            return node, str(value)
        if inv == "swapped_operands":
            new = copy.copy(node)
            new.left, new.right = node.right, node.left
            return node, ast.unparse(new)
        if inv == "wrong_comparator":
            new = copy.copy(node)
            new.ops = [_CMP_SWAP[type(node.ops[0])]()] + list(node.ops[1:])
            return node, ast.unparse(new)
        if inv == "swapped_boolean":
            return node, "False" if node.value is True else "True"
        return None
    if inv in (RECON_KEY, "recon_guard_literal", "recon_return_expr"):
        node = _find_stmt_at(tree, ast.Return, site)
        if node is None:
            return None
        return node, f"return {param}"
    if inv == "recon_assign":
        node = _find_stmt_at(tree, ast.Pass, site)
        if node is None:
            return None
        return node, str(param)  # param is "target = expr"
    if inv == "recon_guard":
        node = _find_stmt_at(tree, ast.If, site)
        if node is None or not isinstance(node.test, ast.Name):
            return None
        return node.test, str(param)  # param is "guard and/or extra"
    return None


def _span_edit_spec(original: str, tree: ast.AST, cand: dict):
    """Fallback edit spec: splice the changed node's replacement
    into the original source by AST position, then take the changed
    lines (with context for uniqueness). Returns (old_text,
    new_text) or None."""
    found = _span_replacement(tree, cand)
    if found is None:
        return None
    node, replacement = found
    new_source = _splice(original, node, replacement)
    if new_source is None:
        return None
    first = node.lineno - 1
    last = node.end_lineno
    return _with_context(original, new_source, first, last)


# ---------------------------------------------------------------------------
# Main driver.
# ---------------------------------------------------------------------------
def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cwd", default=".", help="repo root (test commands run here)")
    parser.add_argument("--file", required=True, help="buggy file, repo-relative (e.g. task.py)")
    parser.add_argument("--function", default="", help="implicated function name (derived from the test file if omitted)")
    parser.add_argument("--test-file", required=True, help="failing test file, repo-relative (e.g. tests/test_task.py)")
    parser.add_argument("--failing-test", required=True, help="command that runs the failing test (exit 0 = pass)")
    parser.add_argument("--regressions", default="", help="command that runs the regression tests (exit 0 = pass); empty skips the gate")
    parser.add_argument("--time-budget", type=float, default=210.0, help="seconds of enumeration before giving up (default 210; the 5-min task budget must still cover orient + gate + submit)")
    parser.add_argument("--per-test-timeout", type=int, default=30, help="seconds per failing-test run (default 30, harness value)")
    parser.add_argument("--regression-timeout", type=int, default=90, help="seconds for the regression command (default 90, gate value)")
    args = parser.parse_args(argv)

    t_start = time.monotonic()
    cwd = os.path.abspath(args.cwd)
    file_path = Path(cwd) / args.file
    test_path = Path(cwd) / args.test_file
    result: dict = {
        "status": "error",
        "file": args.file,
        "function": args.function or None,
        "candidate": None,
        "edit": None,
        "candidates_tried": 0,
        "candidates_total": 0,
        "unappliable": 0,
        "failing_test_passed": False,
        "regressions_passed": False,
        "regressions_run": 0,
        "elapsed_secs": 0.0,
        "timed_out": False,
        "error": None,
    }
    try:
        original = file_path.read_text(encoding="utf-8")
        test_src = test_path.read_text(encoding="utf-8")
    except OSError as e:
        result["error"] = f"cannot read input files: {e}"
        print(json.dumps(result), flush=True)
        return 0

    # The file is restored to its original bytes on every exit path
    # (the agent applies the returned edit itself).
    def restore() -> None:
        try:
            file_path.write_text(original, encoding="utf-8")
        except OSError:
            pass

    try:
        impl: set[str] = {args.function} if args.function else implicated_functions(test_src)
        if not impl:
            result["error"] = "cannot determine the implicated function (pass --function)"
            print(json.dumps(result), flush=True)
            return 0
        result["function"] = sorted(impl)[0] if len(impl) == 1 else sorted(impl)

        tree = ast.parse(original)
        symptom = probe_symptom(original, test_src, cwd)
        combined, counts = build_combined_order(original, impl, symptom)
        result["candidates_total"] = counts["n_combined"]
        result["counts"] = counts
        result["symptom"] = {
            "returns_none": symptom["returns_none"],
            "exception": symptom["exception"],
            "name_error": symptom["name_error"],
            "expected": symptom["expected"],
        }
        deadline = t_start + args.time_budget
        tried = 0
        unappliable = 0
        found = None
        for rank, cand in enumerate(combined, start=1):
            if time.monotonic() > deadline:
                result["timed_out"] = True
                break
            # Write the candidate, test it, move on. The file is
            # fully overwritten per candidate, so no restore is
            # needed between tries; the finally-restore below
            # covers every exit.
            file_path.write_text(cand["source"], encoding="utf-8")
            passed, _out, _secs = _run_cmd(args.failing_test, cwd, args.per_test_timeout)
            tried += 1
            if not passed:
                continue
            if args.regressions:
                # D4 (8 Nov 2026): the regression run must fit in
                # the remaining budget — its own timeout, checked
                # per step (not the summed worst case of all gate
                # steps: the summed need can never be met when the
                # time budget equals it, and it wrongly timed out
                # every gate-accepted candidate in the 8 Nov sim
                # re-run, 0/116). Each later step re-checks its own
                # timeout before starting, so no step ever ends past
                # the deadline. If the budget cannot cover even this
                # step, stop with timed_out instead of running up
                # to ~210 s past the deadline and reporting an
                # unverified fix — or nothing at all.
                if deadline - time.monotonic() < args.regression_timeout:
                    result["timed_out"] = True
                    break
                reg_passed, _rout, _rsecs = _run_cmd(args.regressions, cwd, args.regression_timeout)
                result["regressions_run"] += 1
            else:
                # No regressions: the verify failing-test run must
                # still fit in the remaining budget.
                if deadline - time.monotonic() < args.per_test_timeout:
                    result["timed_out"] = True
                    break
                reg_passed = True
            if not reg_passed:
                continue
            # Gate-accepted as an unparsed candidate. Now build a
            # MINIMAL edit spec for it and verify the applied edit
            # itself passes the failing test and the regressions.
            # A candidate whose edit cannot be built or verified
            # is skipped (counted), not reported.
            spec = _diff_edit_spec(original, cand["source"])
            method = "difflib"
            if spec is None:
                spec = _span_edit_spec(original, tree, cand)
                method = "span"
            if spec is None:
                unappliable += 1
                _log(f"rank {rank} ({cand['detail']}): gate-accepted but no minimal edit spec; skipping")
                continue
            old_text, new_text = spec
            applied = original.replace(old_text, new_text, 1)
            if applied == original:
                unappliable += 1
                continue
            file_path.write_text(applied, encoding="utf-8")
            # D4: the verify failing-test run must fit in the
            # remaining budget (re-check: time passed during the
            # regression run and the spec build).
            if deadline - time.monotonic() < args.per_test_timeout:
                result["timed_out"] = True
                break
            v_passed, _vout, _vsecs = _run_cmd(args.failing_test, cwd, args.per_test_timeout)
            if not v_passed:
                unappliable += 1
                _log(f"rank {rank} ({cand['detail']}): applied edit does not pass the failing test; skipping")
                continue
            if args.regressions:
                # D4: the verify regressions run must fit too.
                if deadline - time.monotonic() < args.regression_timeout:
                    result["timed_out"] = True
                    break
                v_reg, _vrout, _vrsecs = _run_cmd(args.regressions, cwd, args.regression_timeout)
                if not v_reg:
                    unappliable += 1
                    _log(f"rank {rank} ({cand['detail']}): applied edit breaks regressions; skipping")
                    continue
            found = {
                "phase": cand.get("phase", "P1-enum"),
                "inverse": cand["inverse"],
                "site": cand["site"],
                "param": cand["param"],
                "detail": cand.get("detail", ""),
                "rank": rank,
                "edit_method": method,
            }
            result["candidate"] = found
            result["edit"] = {"old_text": old_text, "new_text": new_text}
            result["failing_test_passed"] = True
            result["regressions_passed"] = True
            result["status"] = "fixed"
            break
        result["candidates_tried"] = tried
        result["unappliable"] = unappliable
        if result["status"] == "error":
            result["status"] = "not_found"
    except Exception as e:  # noqa: BLE001 - any internal failure is reported as an error, never a crash with no JSON
        result["error"] = f"{type(e).__name__}: {e}"
        result["status"] = "error"
    finally:
        restore()
    result["elapsed_secs"] = round(time.monotonic() - t_start, 1)
    print(json.dumps(result), flush=True)
    return 0


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "--_probe":
        raise SystemExit(_probe_worker_main())
    raise SystemExit(main())
