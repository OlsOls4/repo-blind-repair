#!/usr/bin/env python3
"""Deterministic inverse-enumeration + reconstruction skill script.

Self-contained (stdlib only). This is the executable backend of the
``enumerate-inverses`` skill: given one buggy file, the function the
failing test calls, and the test commands, it tries single-operator
inverses in the fixed prompt order (v3 combined order: symptom-first
guess, enumeration, reconstruction phase), running the failing test
for each candidate with the fixed-harness semantics, and returns the
first gate-accepted fix as a minimal edit specification.

It NEVER modifies the repository file: candidates are written to the
target file only for the duration of one test run and the original
bytes are restored after every candidate and on exit (try/finally).
The caller (the agent) applies the returned edit with edit_file,
then runs its own gate and submits. Returning an edit spec — rather
than leaving a rewritten file — keeps the patch minimal: candidates
are generated by AST transform + ast.unparse, which would reformat
a real (non-normalized) file if left in place.

Candidate generation is ported from the project's search baseline
(kaggle/search_baseline.py: _Inverter, generate_candidates) and the
v3 reconstruction simulator
(kaggle/simulate_search_guided_v3_recon.py: phase0 / R1 / R2 / R3)
— same orders, same families, same dedup (by patched source, first
occurrence wins). The inverse table is NOT reimplemented: the five
true inverses and the reconstruction guess are exactly the ones the
baseline validated (every invertible operator recovers the fixed
source on generated examples; see search_baseline.py
--validate-inverses).

Inputs are only the buggy source + the failing test: never
bug_class, never the seed, never fixed code. The bug_class label
is used nowhere in this file.

Usage (run by the agent via run_skill_script; runnable directly
for local measurement):
  python3 enumerate_inverses.py --cwd <repo root> --file <rel path>
      --function <name> --test-file <rel path>
      --failing-test "<command>" [--regressions "<command>"]
      [--time-budget 210] [--per-test-timeout 30]
      [--regression-timeout 90]
  --failing-test / --regressions are shell commands run in --cwd
  (e.g. "python -m unittest -v tests.test_task.TestTask.test_failing"
  or "python -m pytest tests/test_task.py::test_failing -q").
  Pass/fail is the command's exit code.

Output: exactly one JSON object on stdout (diagnostics go to
stderr). Status is "fixed" (edit spec verified: the applied edit
passes the failing test AND the regression command), "not_found"
(no gate-accepted candidate within the time budget), or "error".
"""
