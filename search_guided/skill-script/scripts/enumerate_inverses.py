def _site_matches(node: ast.AST, inverse: str) -> bool:
    """True if this node is a candidate site for `inverse` (mirrors
    _Inverter/_count_sites counting, including the negative-int rule
    handled by the caller)."""
    if inverse in ("off_by_one", "wrong_constant"):
        return _is_int_constant(node)
    if inverse == "swapped_operands":
        return isinstance(node, ast.BinOp)
    if inverse == "wrong_comparator":
        return (
            isinstance(node, ast.Compare)
            and bool(node.ops)
            and type(node.ops[0]) in _CMP_SWAP
        )
    if inverse == "swapped_boolean":
        return isinstance(node, ast.Constant) and type(node.value) is bool
    return False


def map_sites_to_functions(tree: ast.AST) -> dict:
    """Map (inverse, site_index) -> (function_name, lineno, col_offset).

    Site indices are DFS pre-order indices among matching nodes, exactly
    as _Inverter/_count_sites count them (a negative int literal is one
    site for off_by_one/wrong_constant; its inner Constant is not a
    separate site). Nodes at module level map to function None.
    """
    mapping: dict = {}
    counters: Counter = Counter()

    def walk(node: ast.AST, func: str | None):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            func = node.name
        for inverse in TRUE_INVERSES:
            if inverse in ("off_by_one", "wrong_constant") and _is_neg_int_literal(node):
                idx = counters[(inverse,)]
                counters[(inverse,)] += 1
                mapping[(inverse, idx)] = (func, node.lineno, node.col_offset)
        # Count this node itself for each inverse, then recurse —
        # except a neg-int literal must not be descended into for the
        # int inverses (its inner Constant is not a separate site).
        for inverse in TRUE_INVERSES:
            if inverse in ("off_by_one", "wrong_constant") and _is_neg_int_literal(node):
                continue  # already counted above; do not descend
            if _site_matches(node, inverse):
                idx = counters[(inverse,)]
                counters[(inverse,)] += 1
                mapping[(inverse, idx)] = (func, node.lineno, node.col_offset)
        # Recurse into children, skipping the inner Constant of a
        # neg-int literal for the int inverses only — handled by
        # counting per-inverse above, so plain recursion is safe
        # here because _site_matches(Constant(1)) is False for the
        # int inverses only when reached via the UnaryOp... no:
        # Constant(1) IS an int constant. Guard it explicitly.
        for child in ast.iter_child_nodes(node):
            if (
                _is_neg_int_literal(node)
                and isinstance(child, ast.Constant)
            ):
                # Inner Constant of a negative literal: it is a site
                # for NO inverse (the UnaryOp is the site for the int
                # inverses; other inverses never match Constant(1)).
                # Skip it entirely.
                continue
            walk(child, func)

    walk(tree, None)
    return mapping


def implicated_functions(test_source: str) -> set[str]:
    """Function names called as <module>.<name> inside test_failing.

    The module name is whatever the test file uses (``task`` in the
    held-out set, any module name in a real repo) — only the
    attribute name matters."""
    tree = ast.parse(test_source)
    names: set[str] = set()
    for node in _iter_dfs(tree):
        if isinstance(node, ast.FunctionDef) and node.name == "test_failing":
            for sub in _iter_dfs(node):
                if (
                    isinstance(sub, ast.Call)
                    and isinstance(sub.func, ast.Attribute)
                    and isinstance(sub.func.value, ast.Name)
                    and sub.func.value.id != "self"  # self.assert* are the test's own assertions, not the code under test
                ):
                    names.add(sub.func.attr)
    return names


# ---------------------------------------------------------------------------
# Symptom probe (ported from simulate_search_guided_v3_recon.py).
# Agent-observable at orient time: the failing-test output shows the
# actual value / the exception, and the test source shows the expected
# literal. One probe, no model call.
# ---------------------------------------------------------------------------
def _implicated_call_and_expected(test_src: str):
    """Return (call_node, expected_literal_or_None)."""
    tree = ast.parse(test_src)
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name == "test_failing":
            for sub in ast.walk(node):
                if not (isinstance(sub, ast.Call) and isinstance(sub.func, ast.Attribute)):
                    continue
                if sub.func.attr in ("assertEqual", "assertAlmostEqual") and len(sub.args) >= 2:
                    try:
                        expected = ast.literal_eval(sub.args[1])
                    except Exception:
                        expected = None
                    return sub.args[0], expected
    return None, None


# D3 (8 Nov 2026): the probe runs buggy repo code, which may
# sys.exit() at import or loop forever. It therefore runs in a
# subprocess with a timeout — never in-process — so a hostile
# module cannot kill main() or hang it past the task budget.
PROBE_TIMEOUT_SECS = 10


def _probe_symptom_impl(buggy: str, test_src: str, cwd: str) -> dict:
    """In-process probe body. Runs ONLY inside the --_probe worker
    subprocess: execs the buggy module and evals the implicated
    call, recording what the agent sees in the failing-test
    output: actual value (None if the function returned nothing),
    exception type, and for a NameError the missing name.
    Expected literal from the test.

    The module is bound under the name the test file actually uses
    for it (``task`` in the held-out set). If the probe cannot run
    (e.g. the call needs repo imports the sandbox cannot satisfy),
    it degrades to raised/unknown rather than failing: Phase 0
    simply does not fire.
    """
    call_node, expected = _implicated_call_and_expected(test_src)
    actual = _RAISED
    exc = None
    name_error = None
    if call_node is not None:
        mod = types.ModuleType("task")
        try:
            if cwd not in sys.path:
                sys.path.insert(0, cwd)
            exec(compile(buggy, "<task>", "exec"), mod.__dict__)  # noqa: S102 - local repo code, same as the agent runs
            base = None
            if isinstance(call_node.func, ast.Attribute) and isinstance(call_node.func.value, ast.Name):
                base = call_node.func.value.id
            namespace = {"task": mod}
            if base:
                namespace[base] = mod
            actual = eval(compile(ast.Expression(call_node), "<t>", "eval"), namespace)  # noqa: S307
        except NameError as e:
            # Two shapes: a name never assigned anywhere in the
            # function -> "name 'x' is not defined"; a name assigned
            # LATER in the function -> UnboundLocalError (a NameError
            # subclass): "local variable 'x' referenced before
            # assignment" (older wording) or "cannot access local
            # variable 'x' where it is not associated with a value"
            # (this Python's wording). Both name the missing
            # variable, exactly as the failing-test output shows it.
            exc = type(e).__name__
            m = (re.search(r"name '(\w+)' is not defined", str(e))
                 or re.search(r"local variable '(\w+)' referenced before assignment", str(e))
                 or re.search(r"cannot access local variable '(\w+)' where it is not associated with a value", str(e)))
            name_error = m.group(1) if m else None
            actual = _RAISED
        except BaseException as e:  # noqa: BLE001 - symptom is the exception type; BaseException so sys.exit() at import is a symptom, not a kill
            exc = type(e).__name__
            actual = _RAISED
    return {
        "actual": None if actual is _RAISED else actual,
        "raised": actual is _RAISED,
        "exception": exc,
        "name_error": name_error,
        "expected": expected,
        "returns_none": actual is None,
    }


def _probe_degraded(test_src: str) -> dict:
    """Raised/unknown probe result: no symptom, Phase 0 does not
    fire. The expected literal is pure AST, so it is still
    recovered here."""
    _call, expected = _implicated_call_and_expected(test_src)
    return {
        "actual": None,
        "raised": True,
        "exception": None,
        "name_error": None,
        "expected": expected,
        "returns_none": False,
    }


def probe_symptom(buggy: str, test_src: str, cwd: str) -> dict:
    """Run the implicated call against the buggy source in a
    subprocess (see _probe_symptom_impl). Any worker failure —
    timeout (infinite loop), crash, or malformed output — degrades
    to raised/unknown instead of propagating: main() always keeps
    going and always prints its JSON result."""
    try:
        proc = subprocess.run(
            [sys.executable, os.path.abspath(__file__), "--_probe"],
            input=json.dumps({"buggy": buggy, "test_src": test_src, "cwd": cwd}),
            capture_output=True, text=True, timeout=PROBE_TIMEOUT_SECS,
        )
        if proc.returncode != 0:
            _log(f"probe worker exited rc={proc.returncode}; degrading to raised/unknown")
            return _probe_degraded(test_src)
        result = json.loads(proc.stdout)
        if not isinstance(result, dict) or "raised" not in result:
            _log("probe worker returned malformed JSON; degrading to raised/unknown")
            return _probe_degraded(test_src)
        return result
    except subprocess.TimeoutExpired:
        _log(f"probe worker timed out after {PROBE_TIMEOUT_SECS}s; degrading to raised/unknown")
        return _probe_degraded(test_src)
    except (OSError, ValueError) as e:
        _log(f"probe worker failed ({type(e).__name__}: {e}); degrading to raised/unknown")
        return _probe_degraded(test_src)


def _probe_worker_main() -> int:
    """--_probe entry point: read {buggy, test_src, cwd} as JSON on
    stdin, run the probe in-process here (this IS the subprocess),
    print exactly one JSON object on stdout, exit 0. Any failure
    inside still prints a degraded JSON object — the parent never
    sees a crash, only a result."""
    try:
        payload = json.load(sys.stdin)
        result = _probe_symptom_impl(payload["buggy"], payload["test_src"], payload["cwd"])
    except BaseException as e:  # noqa: BLE001 - the worker must always answer with JSON
        try:
            result = _probe_degraded(payload.get("test_src", "") if isinstance(payload, dict) else "")
        except BaseException:
            result = {"actual": None, "raised": True, "exception": None,
                      "name_error": None, "expected": None, "returns_none": False}
        _log(f"probe worker internal failure ({type(e).__name__}); returning degraded result")
    print(json.dumps(result), flush=True)
    return 0



