# Deterministic heuristic candidates (no model required)
# ---------------------------------------------------------------------------

# Operator flips, as (ast node class, old symbol, new symbol). BinOp and
# Compare symbols are replaced inside the source segment; BoolOp flips
# "and"/"or" inside the segment; UnaryOp Not drops the "not".
_BINOP_FLIPS = {
    ast.Add: (ast.Sub, "+", "-"),
    ast.Sub: (ast.Add, "-", "+"),
    ast.Mult: (ast.Div, "*", "/"),
    ast.Div: (ast.Mult, "/", "*"),
}
_COMPARE_FLIPS = {
    ast.Lt: (ast.LtE, "<", "<="),
    ast.LtE: (ast.Lt, "<=", "<"),
    ast.Gt: (ast.GtE, ">", ">="),
    ast.GtE: (ast.Gt, ">=", ">"),
    ast.Eq: (ast.NotEq, "==", "!="),
    ast.NotEq: (ast.Eq, "!=", "=="),
}

_PACK_HEADER_RE = re.compile(r"^--- (.+?) \(rung \d+\) ---\s*$")

DEFAULT_MAX_CANDIDATES = 100


def parse_packed_context(context_text: str) -> list[tuple[str, str]]:
    """Split packer output into [(path, content)] in pack order.

    Headers look like ``--- calculator.py (rung 1) ---``. Files whose
    content was truncated by the packer (``[... truncated ...]`` marker)
    are still returned; AST parsing of truncated content will simply
    fail and yield no candidates for that file (a documented limit).
    """
    files: list[tuple[str, str]] = []
    cur_path: str | None = None
    cur_lines: list[str] = []
    for line in context_text.splitlines():
        m = _PACK_HEADER_RE.match(line)
        if m:
            if cur_path is not None:
                files.append((cur_path, "\n".join(cur_lines)))
            cur_path = m.group(1)
            cur_lines = []
        elif cur_path is not None:
            cur_lines.append(line)
    if cur_path is not None:
        files.append((cur_path, "\n".join(cur_lines)))
    return files


def _anchor_old_text(
    content: str, lines: list[str], func_def_lines: dict[int, str],
    lineno: int, line: str,
) -> str | None:
    """Return a uniquely-occurring old_text for ``line``, or None.

    Prefer the bare line; if it occurs more than once (e.g. a bare
    ``return a - b`` shared by two functions), anchor it with its
    enclosing ``def`` line. If neither is unique, return None — the
    candidate is skipped rather than risking an ambiguous application.
    """
    if content.count(line) == 1:
        return line
    # Enclosing function: the nearest def line at or before this line.
    candidates = [d for d in func_def_lines if d <= lineno]
    if candidates:
        def_lineno = max(candidates)
        anchored = func_def_lines[def_lineno] + "\n" + line
        if content.count(anchored) == 1:
            return anchored
    return None


def _heuristic_candidates_for_file(path: str, content: str) -> list[FileEdit]:
    """One-line flip candidates for one packed file, in source order."""
    try:
        tree = ast.parse(content)
    except SyntaxError:
        return []  # truncated / unparsable file: no candidates (honest limit)
    lines = content.splitlines()
    func_def_lines: dict[int, str] = {}
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            func_def_lines[node.lineno] = lines[node.lineno - 1]

    # Collect (lineno, col, old_text, new_text) then sort by source order.
    raw: list[tuple[int, int, str, str]] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Return) or node.value is None:
            continue
        value = node.value
        segment: str | None = None
        flipped: str | None = None
        if isinstance(value, ast.BinOp) and type(value.op) in _BINOP_FLIPS:
            _, old_sym, new_sym = _BINOP_FLIPS[type(value.op)]
            segment = ast.get_source_segment(content, value)
            if segment and old_sym in segment:
                flipped = segment.replace(old_sym, new_sym, 1)
        elif isinstance(value, ast.Compare) and len(value.ops) == 1 \
                and type(value.ops[0]) in _COMPARE_FLIPS:
            _, old_sym, new_sym = _COMPARE_FLIPS[type(value.ops[0])]
            segment = ast.get_source_segment(content, value)
            if segment and old_sym in segment:
                flipped = segment.replace(old_sym, new_sym, 1)
        elif isinstance(value, ast.BoolOp) and isinstance(value.op, (ast.And, ast.Or)):
            old_word, new_word = ("and", "or") if isinstance(value.op, ast.And) else ("or", "and")
            segment = ast.get_source_segment(content, value)
            if segment and old_word in segment.split():
                flipped = segment.replace(old_word, new_word, 1)
        elif isinstance(value, ast.UnaryOp) and isinstance(value.op, ast.Not):
            segment = ast.get_source_segment(content, value)
            if segment and segment.startswith("not "):
                flipped = segment[4:]
        elif isinstance(value, ast.Constant) and isinstance(value.value, bool):
            segment = ast.get_source_segment(content, value)
            if segment in ("True", "False"):
                flipped = "False" if value.value else "True"
        if segment is None or flipped is None or flipped == segment:
            continue
        if value.lineno is None or value.lineno > len(lines):
            continue
        line = lines[value.lineno - 1]
        if segment not in line:
            continue  # multi-line expression: skip, do not guess
        new_line = line.replace(segment, flipped, 1)
        if new_line == line:
            continue
        old_text = _anchor_old_text(content, lines, func_def_lines, value.lineno, line)
        if old_text is None:
            continue
        if "\n" in old_text:
            def_line, bare = old_text.split("\n", 1)
            new_text = def_line + "\n" + new_line
        else:
            new_text = new_line
        raw.append((value.lineno, value.col_offset, old_text, new_text))

    raw.sort()
    edits: list[FileEdit] = []
    seen: set[tuple[str, str]] = set()
    for _, _, old_text, new_text in raw:
        if (old_text, new_text) not in seen:
            seen.add((old_text, new_text))
            edits.append(FileEdit(path=path, old_text=old_text, new_text=new_text))
    return edits


def heuristic_candidates(context_text: str) -> list[list[FileEdit]]:
    """All deterministic candidates, each a one-edit patch, in order."""
    patches: list[list[FileEdit]] = []
    seen: set[tuple[str, str, str]] = set()
    for path, content in parse_packed_context(context_text):
        for edit in _heuristic_candidates_for_file(path, content):
            key = (edit.path, edit.old_text, edit.new_text)
            if key not in seen:
                seen.add(key)
                patches.append([edit])
    return patches


