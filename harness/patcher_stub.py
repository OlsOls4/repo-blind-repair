"""Patch interface + the INFERENCE-ONLY patch generator.

A patch is a list of :class:`FileEdit` (exact old-text -> new-text
replacements). This keeps patch application deterministic, reviewable and
diffable — the regression gate measures exactly what changed.

Inference-only variant (no training, no adapter required)
----------------------------------------------------------
This module is the patch generator for the inference-only agent, which
must work with the declared base model alone
(``gemma-4-12b-it-qat-w4a16-ct``). It has two candidate sources, tried
in this order by :func:`generate_candidates`:

1. **Trained-format model candidates (preferred, when a model is
   available).** This is the ONLY model format the trained adapter
   was taught (see "Format alignment" below). For each implicated
   source file in the packed context, :func:`build_trained_format_prompt`
   formats that single file exactly as training did, the model
   generates the full fixed file, and :func:`fixed_file_to_edits`
   turns the generated file into ``FileEdit`` objects by diffing it
   against the original. The caller supplies the model as a callable
   (``model_fn(prompt) -> str``); this module never calls a paid API,
   a teacher model, or the network, and it never loads an adapter.
   If no ``model_fn`` is supplied, this source is simply skipped —
   it is not faked.

   The legacy ``FILE:``/``OLD:``/``NEW:`` prompt builder
   (:func:`build_repair_prompt`) and parser
   (:func:`parse_model_patch_output`) are RETAINED for backwards
   compatibility only (old tests, old saved outputs). They are NO
   LONGER used for model output anywhere: a trained adapter was
   never trained to emit ``FILE:``/``OLD:``/``NEW:`` blocks, and
   demanding them guaranteed unparsable output (diagnosed 1 Nov
   2026: rung-1 generation ran the full 512 tokens and produced
   nothing parsable). Do not reintroduce them as the model format.

2. **Deterministic one-line heuristic candidates (fallback, always
   available locally).** When no model is available, candidates are
   generated by AST analysis of the packed files: single-operator flips
   in ``return`` expressions (``-`` <-> ``+``, ``*`` <-> ``/``,
   ``<`` <-> ``<=``, ``>`` <-> ``>=``, ``==`` <-> ``!=``,
   ``and`` <-> ``or``, ``not x`` -> ``x``, ``True`` <-> ``False``).
   Every candidate is exactly one line in exactly one file, anchored
   so its old text occurs exactly once (see :func:`apply_edits`).
   NOTE: the dev-set evaluation (``kaggle/eval_dev.py``) deliberately
   does NOT use these heuristics — its fix rate is the adapter's
   alone. They survive here only as the inference-only variant's
   local fallback.

Format alignment — why the model format is what it is (1 Nov 2026)
------------------------------------------------------------------
Training (``kaggle/full_train_manual_lora.py`` ``to_text_example``)
taught exactly one text shape:

    Fix this Python bug (bug class: <label>):
    <buggy_code>
    Fixed code:
    <fixed_code>

The adapter therefore knows how to continue a "Fixed code:" cue
with a full fixed file, and nothing else. Inference CANNOT supply
the bug class — real tasks carry no label, and inventing one would
be a fabricated input — so the inference prompt drops it:

    Fix this Python bug:
    <implicated buggy file>
    Fixed code:

That omission is a small, documented distribution shift (header
without label vs header with label); everything after "Fixed
code:" is exactly the trained continuation task. Multi-file
contexts are handled by generating PER implicated source file,
one file per generation, because training is single-file: the
model never saw a multi-file packed context, so it is never asked
to repair one. Test files are never generation targets (a test
file is not the bug), and empty files are skipped, not generated.

Honest limits — read before claiming anything about repair quality
-------------------------------------------------------------------
* The heuristic source is deliberately narrow. It can only fix bugs
  that are a single flipped operator / boolean in a ``return``
  expression. It cannot fix multi-line logic errors, wrong constants,
  missing branches, wrong API calls, new-file additions, or any bug
  whose fix is not a one-line flip. Most real bugs are outside it.
* A generated fixed file must fit in the generation budget: if
  ``max_new_tokens`` truncates the file mid-way, it fails
  ``ast.parse`` and yields no candidate. That is a silent-looking
  no_patch, not a gate rejection — size the budget above the
  longest file you expect to repair.
* Candidate order is source order (file order in the pack, then line
  order), NOT a quality ranking. The regression gate — not this
  module — is what decides whether a candidate is any good: a
  candidate is only kept if the failing test passes AND the capped
  regression suite stays green (see ``regression_gate.py``). A
  candidate that fixes the failing test but breaks a regression test
  is rejected and rolled back.
* ``generate_patch`` returns only the FIRST candidate. That is the
  single-candidate interface the scope ladder's ``patch_fn`` expects.
  The full search (try each candidate through the gate, minimal-diff
  first) lives in ``inference_agent.run_inference_only`` — use that,
  not bare ``generate_patch``, for a real repair attempt.
* No repair-quality claim is made here. No score, timing, or success
  rate is asserted for this generator: it has only been exercised
  locally on the toy ``demo_repo/`` (see tests). Scorer / vLLM
  serving of the base model is UNPROVEN, and the ``agent.yaml``
  schema is UNVERIFIED against the competition starter notebook.

History: ``generate_patch`` used to raise ``NotImplementedError`` as
a placeholder for the future trained LoRA generator. It no longer
does: the inference-only generator below returns ``None`` when it
has no candidate, so "no patch at this rung" is explicit and a
missing model is never mistaken for a silent success. The LoRA
variant is separate — it will use its own generator, not this one.
"""
from __future__ import annotations

import ast
import re
from dataclasses import dataclass

# ---------------------------------------------------------------------------
# Patch primitives (unchanged from the original stub)
# ---------------------------------------------------------------------------


@dataclass
class FileEdit:
    path: str  # path relative to the repo root
    old_text: str  # exact text to replace; must occur exactly once
    new_text: str


def _clear_pycache(repo_root: str, path: str) -> None:
    """Delete stale bytecode for a rewritten file.

    .pyc invalidation uses source mtime (second resolution) + size. A
    one-character patch (``-`` -> ``+``) keeps the size identical and can
    land in the same second as the previous write, so a stale .pyc would
    otherwise make tests run the OLD code. Deleting the cache entry is
    the robust fix; it costs one recompile per changed file.
    """
    import glob
    import os

    directory, filename = os.path.split(os.path.join(repo_root, path))
    stem = os.path.splitext(filename)[0]
    cache_dir = os.path.join(directory, "__pycache__")
    for cached in glob.glob(os.path.join(cache_dir, stem + ".*.pyc")):
        try:
            os.remove(cached)
        except OSError:
            pass


def apply_edits(repo_root: str, edits: list[FileEdit]) -> dict[str, str]:
    """Apply edits, returning {path: original_content} for rollback.

    Raises ValueError if an old_text does not occur exactly once, so a
    stale or ambiguous patch can never be half-applied silently.
    """
    import os

    originals: dict[str, str] = {}
    for edit in edits:
        full = os.path.join(repo_root, edit.path)
        with open(full, encoding="utf-8") as fh:
            content = fh.read()
        if edit.path not in originals:
            originals[edit.path] = content
        if content.count(edit.old_text) != 1:
            # Roll back anything already applied in this call.
            rollback_edits(repo_root, originals)
            raise ValueError(
                f"old_text for {edit.path} occurs "
                f"{content.count(edit.old_text)} times (expected exactly 1)"
            )
        with open(full, "w", encoding="utf-8") as fh:
            fh.write(content.replace(edit.old_text, edit.new_text))
        _clear_pycache(repo_root, edit.path)
    return originals


def rollback_edits(repo_root: str, originals: dict[str, str]) -> None:
    """Restore files to their original contents."""
    import os

    for path, content in originals.items():
        with open(os.path.join(repo_root, path), "w", encoding="utf-8") as fh:
            fh.write(content)
        _clear_pycache(repo_root, path)


