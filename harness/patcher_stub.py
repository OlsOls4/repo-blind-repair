TRAINED_PROMPT_HEADER = "Fix this Python bug:\n"
TRAINED_PROMPT_CUE = "\nFixed code:\n"


def build_trained_format_prompt(buggy_content: str) -> str:
    """Build the exact inference prompt matching the trained format.

    Training text is ``Fix this Python bug (bug class: <label>):\\n
    <buggy_code>\\nFixed code:\\n<fixed_code>``. At inference the
    label is omitted (real tasks carry none, and inventing one
    would be a fabricated input), giving::

        Fix this Python bug:
        <implicated buggy file>
        Fixed code:

    Trailing newlines of the file are stripped before the cue so the
    prompt has exactly one newline between file content and
    "Fixed code:"; interior content is untouched. The caller
    generates greedily after this prompt; the model continues with
    the fixed file, as it was trained to do.
    """
    return (TRAINED_PROMPT_HEADER + buggy_content.rstrip("\n")
            + TRAINED_PROMPT_CUE)


def is_test_file(path: str) -> bool:
    """True if ``path`` is a test file, never a repair target.

    A test file exercises the bug; it is not the bug. Excluded:
    basenames starting with ``test_``, any ``tests`` path component,
    and ``conftest.py`` (test support, not product code).
    """
    parts = path.replace("\\", "/").split("/")
    base = parts[-1]
    return (base.startswith("test_") or "tests" in parts
            or base == "conftest.py")


def clean_generated_file(text: str) -> str:
    """Extract a plausible fixed file from raw model output.

    Truncates at a repeated training header (the model continuing
    past the file into a new example) and strips trailing blank
    lines. Returns "" for empty/whitespace-only output. Interior
    content is untouched; no reformatting, no guessing.

    Also truncates at a bare ``Fixed code:`` cue line (diagnosed
    1 Nov 2026): training never taught the model an EOS after the
    fixed file, so on held-out tasks it runs to the token cap and
    loops into repeated ``Fixed code:`` blocks of corrupted
    fragments. The cue line itself can never appear inside a genuine
    fixed file (it is the prompt cue, not code), so the first block
    before it is the candidate file and everything after it is
    regurgitation to discard. Without this cut, the whole output
    fails to parse and yields no candidate at all.
    """
    lines: list[str] = []
    for line in text.splitlines():
        if line.startswith("Fix this Python bug"):
            break
        if line.strip() == "Fixed code:":
            break
        lines.append(line)
    while lines and not lines[-1].strip():
        lines.pop()
    if not lines:
        return ""
    return "\n".join(lines) + "\n"


def _verify_edits(original: str, edits: list[FileEdit],
                  gen_lines: list[str]) -> bool:
    """Simulate applying ``edits``; True iff the result matches.

    Uses the same exactly-once rule as :func:`apply_edits`.
    Comparison is by lines (trailing-newline differences at EOF are
    not a repair and must not fail verification).
    """
    text = original
    for edit in edits:
        if text.count(edit.old_text) != 1:
            return False
        text = text.replace(edit.old_text, edit.new_text, 1)
    return text.splitlines() == gen_lines


def fixed_file_to_edits(path: str, original: str,
                        generated: str) -> list[FileEdit] | None:
    """Turn a generated full fixed file into a gate-ready patch.

    Returns ``None`` (no candidate) when the generation is empty,
    identical to the original (modulo trailing newlines), or does
    not parse as Python — a truncated or prose generation must
    never reach the gate as a patch. Otherwise returns a list of
    ``FileEdit`` built from difflib hunks: each changed block
    becomes one edit whose old text occurs exactly once in the
    original. An insertion anchors on its neighbouring line. If any
    block cannot be anchored uniquely, or the simulated application
    does not reproduce the generated file, the whole thing falls
    back to ONE whole-file edit (old = entire original, new =
    entire generated file), which is exact by construction and
    still atomic (a single write) through the unchanged gate.
    The gate — not this function — decides acceptance.
    """
    import difflib

    cleaned = clean_generated_file(generated)
    if not cleaned.strip():
        return None
    if cleaned.rstrip("\n") == original.rstrip("\n"):
        return None
    try:
        ast.parse(cleaned)
    except SyntaxError:
        return None

    orig_lines = original.splitlines()
    gen_lines = cleaned.splitlines()
    matcher = difflib.SequenceMatcher(None, orig_lines, gen_lines,
                                      autojunk=False)
    edits: list[FileEdit] = []
    for tag, i1, i2, j1, j2 in matcher.get_opcodes():
        if tag == "equal":
            continue
        if i1 == i2:
            # Pure insertion: anchor on a neighbouring original line.
            if i1 > 0:
                anchor = orig_lines[i1 - 1]
                old_text = anchor
                new_text = anchor + "\n" + "\n".join(gen_lines[j1:j2])
            elif orig_lines:
                anchor = orig_lines[0]
                old_text = anchor
                new_text = "\n".join(gen_lines[j1:j2]) + "\n" + anchor
            else:
                return [FileEdit(path=path, old_text=original,
                                 new_text=cleaned)]
            if original.count(old_text) != 1:
                return [FileEdit(path=path, old_text=original,
                                 new_text=cleaned)]
            edits.append(FileEdit(path=path, old_text=old_text,
                                  new_text=new_text))
        else:
            old_text = "\n".join(orig_lines[i1:i2])
            new_text = "\n".join(gen_lines[j1:j2])
            if original.count(old_text) != 1:
                return [FileEdit(path=path, old_text=original,
                                 new_text=cleaned)]
            edits.append(FileEdit(path=path, old_text=old_text,
                                  new_text=new_text))
    if not edits:
        return None
    if _verify_edits(original, edits, gen_lines):
        return edits
    return [FileEdit(path=path, old_text=original, new_text=cleaned)]


