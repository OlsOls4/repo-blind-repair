def generate_candidates(
    context_text: str,
    rung: int,
    model_fn=None,
    max_candidates: int = DEFAULT_MAX_CANDIDATES,
) -> list[list[FileEdit]]:
    """Ordered repair candidates for one rung, minimal-diff first.

    Order: trained-format model candidates first (one per implicated
    source file in pack order, if ``model_fn`` is supplied and its
    generated fixed file diffs into a patch), then deterministic
    heuristic one-line patches in source order. Every candidate is
    gate-filtered by the caller (``inference_agent.run_inference_only``
    or the scope ladder); this function never claims a candidate is
    correct. Test files and empty files are never model targets.

    ``model_fn`` is ``prompt -> str`` (trained-format prompt, see
    :func:`build_trained_format_prompt`, to a full fixed file).
    If it raises, the error propagates — a model failure must not be
    silently downgraded to "no patch". If it returns empty,
    identical, or unparsable output for a file, that file contributes
    no model candidate and heuristics are still returned.
    """
    candidates: list[list[FileEdit]] = []
    seen: set[tuple[tuple[str, str, str], ...]] = set()

    def _add(patch: list[FileEdit]) -> None:
        key = tuple((e.path, e.old_text, e.new_text) for e in patch)
        if patch and key not in seen:
            seen.add(key)
            candidates.append(patch)

    if model_fn is not None:
        for path, content in parse_packed_context(context_text):
            if is_test_file(path) or not content.strip():
                continue
            prompt = build_trained_format_prompt(content)
            edits = fixed_file_to_edits(path, content, model_fn(prompt))
            if edits is not None:
                _add(edits)
    for patch in heuristic_candidates(context_text):
        _add(patch)
    return candidates[:max_candidates]


def generate_patch(
    context_text: str,
    rung: int,
    model_fn=None,
) -> list[FileEdit] | None:
    """Inference-only patch generator (scope-ladder ``patch_fn``).

    Returns the first candidate (trained-format model candidate if
    one diffed into a patch, else the first heuristic one-line
    patch), or ``None`` when there is no candidate at this rung. It
    NEVER raises ``NotImplementedError`` any more: no candidate is
    an explicit ``None``, not a missing model.

    For a real attempt, prefer ``inference_agent.run_inference_only``,
    which tries every candidate through the regression gate instead of
    just this first one.
    """
    candidates = generate_candidates(context_text, rung, model_fn=model_fn, max_candidates=1)
    return candidates[0] if candidates else None
