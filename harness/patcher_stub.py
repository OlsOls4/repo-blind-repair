MODEL_OUTPUT_FORMAT = """FILE: <path relative to the repo root>
OLD:
<exact old text, as it appears in the file>
NEW:
<exact new text to replace it with>
"""

# A model reply may contain several FILE blocks; together they are ONE
# patch (a list of FileEdit). Blocks are separated by a FILE: header.
_FILE_HEADER_RE = re.compile(r"^FILE:\s*(\S+)\s*$")


def build_repair_prompt(
    context_text: str,
    rung: int,
    failing_test_id: str = "",
    error_message: str = "",
) -> str:
    """Format a repair prompt for the base model alone (no adapter).

    The prompt instructs the model to output ONLY patch blocks in the
    format parsed by :func:`parse_model_patch_output`, with a minimal
    diff (fewest lines changed). It makes no claim about any adapter:
    this variant has none.
    """
    header = (
        "You are repairing a Python bug. Use ONLY the code below.\n"
        "Output ONLY patch blocks in this exact format, one block per file edit:\n\n"
        + MODEL_OUTPUT_FORMAT
        + "\nRules:\n"
        "- Change as few lines as possible; prefer a single-line fix.\n"
        "- OLD text must match the file exactly, including indentation.\n"
        "- Do not explain, do not add commentary, do not invent files.\n"
        "- If you cannot identify a fix, output nothing.\n"
    )
    if failing_test_id:
        header += f"\nFailing test: {failing_test_id}\n"
    if error_message:
        header += f"Error: {error_message}\n"
    header += f"\nScope-ladder rung: {rung} (1 = trace files, 2 = imports/callers, 3 = wider search).\n"
    return header + "\nCode:\n" + context_text


def parse_model_patch_output(text: str) -> list[FileEdit] | None:
    """Parse a model reply in the FILE:/OLD:/NEW: format.

    Returns ``None`` for empty, malformed, or vacuous output (no blocks,
    missing OLD/NEW section, empty OLD text, OLD == NEW, or a ``..`` /
    absolute path, which must never reach :func:`apply_edits`).
    Parsing success says nothing about correctness — the regression
    gate still has to accept the patch.
    """
    if not text or not text.strip():
        return None
    edits: list[FileEdit] = []
    path: str | None = None
    section: str | None = None  # "old" | "new"
    old_lines: list[str] = []
    new_lines: list[str] = []

    def flush() -> bool:
        """Flush the current block into edits; False if invalid."""
        nonlocal path, old_lines, new_lines
        if path is None or section != "new":
            return False
        old_text = "\n".join(old_lines).rstrip("\n")
        new_text = "\n".join(new_lines).rstrip("\n")
        if not old_text or old_text == new_text:
            return False
        if path.startswith("/") or ".." in path.split("/"):
            return False
        edits.append(FileEdit(path=path, old_text=old_text, new_text=new_text))
        return True

    for raw_line in text.splitlines():
        m = _FILE_HEADER_RE.match(raw_line.strip())
        if m:
            if path is not None and not flush():
                return None
            path = m.group(1)
            section = None
            old_lines, new_lines = [], []
            continue
        stripped = raw_line.strip()
        if stripped == "OLD:" and path is not None and section is None:
            section = "old"
            continue
        if stripped == "NEW:" and path is not None and section == "old":
            section = "new"
            continue
        if section == "old":
            old_lines.append(raw_line)
        elif section == "new":
            new_lines.append(raw_line)
        elif raw_line.strip():
            # Text outside any block/format section: malformed.
            return None
    if path is not None and not flush():
        return None
    return edits or None


